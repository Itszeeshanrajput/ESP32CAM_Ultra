#!/usr/bin/env python3
"""Compress ui/index.html into web_ui.h (gzip -> C array). Run after every UI edit:  python3 tools/build_ui.py"""
import gzip, pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "ui" / "index.html").read_text(encoding="utf-8")
html = re.sub(r">\s+<", "><", html)              # light minify between tags (safe: no <pre> in static markup)
gz = gzip.compress(html.encode("utf-8"), 9)
rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
out = "#pragma once\n// GENERATED by tools/build_ui.py - do not edit by hand\n#include <pgmspace.h>\n"
out += f"const size_t WEB_UI_GZ_LEN = {len(gz)};\nconst uint8_t WEB_UI_GZ[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n"
(root / "web_ui.h").write_text(out)
print(f"web_ui.h written: {len(html)} bytes html -> {len(gz)} bytes gzip")
